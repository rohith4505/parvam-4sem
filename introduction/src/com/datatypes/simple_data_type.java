package com.datatypes;

public class simple_data_type {
	public static void main(String[] args) {
		byte age = 123;
		boolean tr = true;
		float fr = 234.09f;
		double d = 45.06;
		char fff = 'h';
		String g = "hello";
		System.out.println("age is: "+age);
		System.out.println("bool value: "+tr);
		System.out.println("folating value:"+fr);
		System.out.println("double: "+d);
		System.out.println("char value: "+fff);
		System.out.println("string : "+g);
		
	}

}
